/**
 * Computes deterministic KPI metrics directly from the customer dataset.
 * Guarantees 100% internal consistency between KPI summary cards and directory data.
 */
export function calculateCustomerKpis(customers: CustomerRecord[]) {
  const totalCustomers = customers.length
  if (totalCustomers === 0) {
    return {
      totalCustomers: 0,
      highValueCustomers: 0,
      atRiskCustomers: 0,
      averageClv: 0,
    }
  }

  const highValueCustomers = customers.filter((c) => c.predictedClv >= 10000).length
  const atRiskCustomers = customers.filter((c) => c.churnRisk === 'high').length
  const totalClv = customers.reduce((acc, c) => acc + c.predictedClv, 0)
  const averageClv = Math.round(totalClv / totalCustomers)

  return {
    totalCustomers,
    highValueCustomers,
    atRiskCustomers,
    averageClv,
  }
}
