import { Sparkles, AlertTriangle, ShieldAlert, PieChart } from 'lucide-react'
import { Card } from '@/components/ui/Card'
import { formatCurrency, formatPercent } from '@/lib/formatters'
import type { InsightKpiSummary } from '../types'

interface InsightKpiCardsProps {
  summary: InsightKpiSummary
}

export function InsightKpiCards({ summary }: InsightKpiCardsProps) {
  const cards = [
    {
      id: 'kpi-total-insights',
      title: 'Active Intelligence Signals',
      value: `${summary.totalInsights} Insights`,
      context: 'Deterministic rules evaluated across 36 cohort accounts',
      icon: Sparkles,
      highlight: false,
    },
    {
      id: 'kpi-high-priority',
      title: 'High-Priority Interventions',
      value: `${summary.highPriorityCount} Critical Actions`,
      context: 'Immediate account outreach & retention actions required',
      icon: AlertTriangle,
      highlight: summary.highPriorityCount > 0,
      highlightVariant: 'warning',
    },
    {
      id: 'kpi-at-risk-clv',
      title: 'Gross CLV at Churn Risk',
      value: formatCurrency(summary.totalAtRiskClv),
      context: 'High-churn accounts (8 accounts with >65% churn risk)',
      icon: ShieldAlert,
      highlight: true,
      highlightVariant: 'destructive',
    },
    {
      id: 'kpi-enterprise-skew',
      title: 'Enterprise Concentration',
      value: formatPercent(summary.enterpriseClvConcentration),
      context: 'CLV generated by top 22.2% of accounts (8 Enterprise accounts)',
      icon: PieChart,
      highlight: false,
    },
  ]

  return (
    <div className="grid gap-3 sm:gap-4 grid-cols-1 sm:grid-cols-2 lg:grid-cols-4">
      {cards.map((card) => {
        const Icon = card.icon
        const isDestructive = card.highlightVariant === 'destructive'
        const isWarning = card.highlightVariant === 'warning'

        return (
          <Card
            key={card.id}
            className={`p-3.5 sm:p-4 flex flex-col justify-between transition-colors bg-card ${
              isDestructive
                ? 'border-destructive/40 ring-1 ring-destructive/10'
                : isWarning
                  ? 'border-amber-500/40 ring-1 ring-amber-500/10'
                  : 'hover:border-border-strong'
            }`}
          >
            <div className="flex items-center justify-between pb-2">
              <span className="text-xs font-medium text-muted-foreground">{card.title}</span>
              <div
                className={`p-1.5 rounded-md border ${
                  isDestructive
                    ? 'bg-destructive/10 border-destructive/20 text-destructive'
                    : isWarning
                      ? 'bg-amber-500/10 border-amber-500/20 text-amber-700'
                      : 'bg-muted/50 border-border/80 text-primary'
                }`}
              >
                <Icon className="h-4 w-4" />
              </div>
            </div>

            <div>
              <div className="text-xl sm:text-2xl font-bold tracking-tight text-foreground tabular-nums">
                {card.value}
              </div>
              <p className="text-[11px] text-muted-foreground mt-1 leading-snug">{card.context}</p>
            </div>
          </Card>
        )
      })}
    </div>
  )
}
